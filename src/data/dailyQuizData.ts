// Helper to get daily quiz for any given date
export function getDailyQuizForDate(dateStr: string): DailyQuizDay {
  const found = DAILY_QUIZZES_ARCHIVE.find((q) => q.date === dateStr);
  if (found) return found;

  // Fallback to rotating question pool dynamically so any date has a valid 5-question challenge
  const hash = dateStr.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  const baseIndex = hash % DAILY_QUIZZES_ARCHIVE.length;
  const base = DAILY_QUIZZES_ARCHIVE[baseIndex];

  return {
    ...base,
    date: dateStr,
    titleEn: `Daily Speed Drill (${dateStr})`,
    titleHi: `दैनिक स्पीड टेस्ट (${dateStr})`,
  };
}

