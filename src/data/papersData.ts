function createQ(
  id: string,
  section: SubjectType,
  questionNumber: number,
  topic: string,
  difficulty: 'Easy' | 'Moderate' | 'Hard',
  textEn: string,
  textHi: string,
  optionsEn: [string, string, string, string],
  optionsHi: [string, string, string, string],
  correctOption: number,
  explanationEn: string,
  explanationHi: string
): Question {
  return {
    id,
    section,
    questionNumber,
    topic,
    difficulty,
    textEn,
    textHi,
    optionsEn,
    optionsHi,
    correctOption,
    explanationEn,
    explanationHi,
  };
}

